package io.github.DekkerDing.ecommerce.domain.coupon;

/**
 * 优惠券类型枚举
 * Coupon Type Enum
 */
public enum CouponType {

    /**
     * 满减券
     * Full reduction coupon
     */
    FULL_REDUCTION,

    /**
     * 折扣券
     * Percentage discount coupon
     */
    DISCOUNT,

    /**
     * 免邮券
     * Free shipping coupon
     */
    FREE_SHIPPING
}
